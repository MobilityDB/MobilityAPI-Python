"""Command codegen writes mobilityapi/catalog_gen.py, the dispatcher's table of
MEOS functions, from the MEOS-API catalog.

meos-idl.json is the machine-readable description of the MEOS C library that
MobilityDB/MEOS-API derives from the MEOS headers and sources, and that every
binding in the ecosystem generates from. Reading it here is what makes this
tier a projection of the same catalog as MobilityAPI's Go tier, PyMEOS-CFFI
and the rest, rather than a reader of MEOS's C with a parse of its own.

This is the Python twin of MobilityAPI's tools/codegen/main.go: the same
flags, the same table-from-catalog projection, the same CI check.

Usage:

    python3 tools/codegen.py -catalog <meos-idl.json> -o mobilityapi/catalog_gen.py

The catalog is derived, never committed: CI derives it from MobilityDB master
with MobilityDB/MEOS-API's provision-meos action, regenerates this file against
it and refuses a difference, so a function MEOS gains, loses or changes reaches
this tier as a failing check rather than as silence.

The table holds, for every function the catalog states as exposable, the
catalog's own entry restricted to the keys the dispatcher reads (name,
category, params, returnType, network, wire and doc), so
FunctionSignature.from_catalog_entry reads the table exactly as it reads the
catalog.
"""

from __future__ import annotations

import argparse
import json
import pprint
import sys
from pathlib import Path

# The keys of a catalog function the dispatcher reads. Every one but doc is
# required, and an entry without one stops the generator.
REQUIRED = ("name", "category", "params", "returnType", "network", "wire")
OPTIONAL = ("doc",)

HEADER = '''\
"""The MEOS functions the dispatcher serves.

Code generated by tools/codegen.py from the MEOS-API catalog. DO NOT EDIT.

Regenerate with:

    python3 tools/codegen.py -catalog <meos-idl.json> -o mobilityapi/catalog_gen.py

One entry per function the catalog states as exposable, ordered by name: the
catalog's own entry restricted to the keys FunctionSignature.from_catalog_entry
reads.
"""

FUNCTIONS = (
'''


def exposable_functions(catalog: dict) -> list[dict]:
    """The catalog entry of every exposable function, ordered by name.

    Mirrors #mathOperations of MobilityAPI's tools/codegen/main.go: the
    selection is the function's own catalog metadata and nothing else.
    """
    out = []
    for entry in catalog["functions"]:
        missing = [k for k in REQUIRED if k not in entry]
        if missing:
            raise KeyError(
                f"the catalog function {entry.get('name', '?')!r} carries no "
                f"{', '.join(missing)}, which the dispatcher reads")
        if not entry["network"]["exposable"]:
            continue
        kept = {k: entry[k] for k in REQUIRED}
        kept.update({k: entry[k] for k in OPTIONAL if k in entry})
        out.append(kept)
    out.sort(key=lambda e: e["name"])
    return out


def render(functions: list[dict]) -> str:
    """The source of catalog_gen.py for these entries.

    Mirrors #render of MobilityAPI's tools/codegen/main.go, which writes the
    Go table the same way: a generated header, then one entry per line group.
    """
    parts = [HEADER]
    for entry in functions:
        text = pprint.pformat(entry, width=88, sort_dicts=False)
        parts.append("    " + text.replace("\n", "\n    ") + ",\n")
    parts.append(")\n")
    return "".join(parts)


def fail(message: str) -> int:
    """Report on stderr and answer the failing exit status, as #fail of
    MobilityAPI's tools/codegen/main.go does."""
    print(f"codegen: {message}", file=sys.stderr)
    return 1


def main(argv: list[str] | None = None) -> int:
    """Read the catalog, project it and write the table, as #main of
    MobilityAPI's tools/codegen/main.go does."""
    parser = argparse.ArgumentParser(prog="codegen")
    parser.add_argument("-catalog", type=Path, default=Path("meos-idl.json"),
                        help="the MEOS-API catalog")
    parser.add_argument("-o", type=Path,
                        default=Path("mobilityapi") / "catalog_gen.py",
                        help="file to write")
    args = parser.parse_args(argv)

    try:
        catalog = json.loads(args.catalog.read_text())
    except (OSError, ValueError) as err:
        return fail(f"{args.catalog}: {err}")
    try:
        functions = exposable_functions(catalog)
    except KeyError as err:
        return fail(f"{args.catalog}: {err}")
    if not functions:
        return fail(f"{args.catalog} states no function as exposable: it is "
                    "derived without the MobilityDB sources, or it is not a "
                    "MEOS-API catalog")

    args.o.write_text(render(functions))
    print(f"codegen: {len(functions)} exposable functions of "
          f"{len(catalog['functions'])} written to {args.o}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
